const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => window.localStorage.getItem('tseba-language') === 'st' ? 'st' : 'en');

  const changeLanguage = useCallback((nextLanguage) => {
    if (!['en', 'st'].includes(nextLanguage)) return;
    setLanguageState(nextLanguage);
    window.localStorage.setItem('tseba-language', nextLanguage);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage: changeLanguage,
    t: (text) => language === 'st' ? translations[text] || text : text,
  }), [changeLanguage, language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider');
  return context;
}

export function localizeAttraction(attraction, language) {
  if (language !== 'st') return attraction;
  const translation = attractionTranslations[attraction.id];
  if (!translation) return attraction;
  return { ...attraction, ...translation };
}
